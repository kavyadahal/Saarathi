
# 1. Store a temperature in Celsius
celsius = 30

# 2. Convert to Fahrenheit and print both
fahrenheit = celsius * 9 / 5 + 32
print(celsius, "C =", fahrenheit, "F")

# 3. Is it a hot day?
print("Hot day?", celsius > 28)

# 4. STRETCH: convert Fahrenheit back to Celsius — do you get 30 again?
back_to_c = (fahrenheit - 32) * 5 / 9
print("Back to C:", back_to_c)

